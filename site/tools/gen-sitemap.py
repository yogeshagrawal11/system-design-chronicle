#!/usr/bin/env python3
"""Generate sitemap.xml for The System Design Chronicle.

The site ships a static pre-rendered page per content item at a pretty folder
URL (e.g. ``/design/url-shortener/``) generated by ``tools/gen-pages.js``. Those
pages carry per-page meta + OG tags and redirect real browsers into the hash SPA.
This sitemap lists the crawlable static URLs (plus the site root) so search
engines can index each item.

Usage:
    python3 tools/gen-sitemap.py [BASE_URL]

BASE_URL defaults to https://sd.agentic-solutions.net/ (trailing slash kept).
Run from the ``site/`` directory (or anywhere — paths are resolved relative to
this file). Run AFTER gen-pages.js so IDs match the generated pages.
"""
import datetime
import os
import sys

SITE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_BASE = "https://sd.agentic-solutions.net/"

# kind -> static pretty-folder prefix served by gen-pages.js. The sitemap is
# built by scanning the generated folders directly, so it always matches the
# pages gen-pages.js actually produced (including items whose data file
# registers more than one entry).
CONTENT_KINDS = ["concept", "design", "company", "paper"]

# Site root (the SPA home). List/tool views live behind hash routes that crawlers
# ignore, so only the root is listed here as a crawlable entry point.
STATIC_ROUTES = [
    ("", "1.0"),
]


def collect():
    urls = []  # (loc_path, priority) — loc_path is appended to base_url
    urls.extend(STATIC_ROUTES)

    for kind in CONTENT_KINDS:
        kind_dir = os.path.join(SITE_DIR, kind)
        if not os.path.isdir(kind_dir):
            continue
        ids = [
            d
            for d in os.listdir(kind_dir)
            if os.path.isfile(os.path.join(kind_dir, d, "index.html"))
        ]
        for cid in sorted(ids):
            # Trailing slash: GitHub Pages serves <kind>/<id>/index.html here.
            urls.append((f"{kind}/{cid}/", "0.6"))

    return urls


def build(base_url):
    today = datetime.date.today().isoformat()
    urls = collect()
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ]
    for frag, prio in urls:
        loc = base_url + frag
        loc = loc.replace("&", "&amp;")
        lines.append("  <url>")
        lines.append(f"    <loc>{loc}</loc>")
        lines.append(f"    <lastmod>{today}</lastmod>")
        lines.append(f"    <priority>{prio}</priority>")
        lines.append("  </url>")
    lines.append("</urlset>")
    lines.append("")
    return "\n".join(lines), len(urls)


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_BASE
    if not base.endswith("/"):
        base += "/"
    xml, n = build(base)
    out = os.path.join(SITE_DIR, "sitemap.xml")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(xml)
    print(f"Wrote {out} with {n} URLs (base: {base})")


if __name__ == "__main__":
    main()
